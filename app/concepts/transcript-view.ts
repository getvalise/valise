import type { TranscriptTurn } from "./transcripts";

/**
 * How the console reads a transcript: pure functions over turns, shared by
 * the route and its tests. Nothing here touches D1.
 *
 * Three quarters of a distilled Claude Code session are tool calls (1,243 of
 * 1,779 turns across 21 sessions in this repo, 2026-11-06), in runs of two at
 * the median and up to 28. Listing each as its own row buries the eleven
 * prompts a person actually wrote, so a run of tool turns folds into one block
 * and every human turn opens an exchange. docs/design/transcripts.md.
 */

/** Idle time between two turns that the reader is shown as a divider. */
export const GAP_SECONDS = 10 * 60;

export type ToolCount = { tool: string; count: number };

/**
 * Text a client writes into the conversation as a user message although the
 * person did not type it: a background task finishing, a slash command and
 * its output, a `!` shell command, the summary that opens a compacted
 * session, an interruption. Measured on the owner's sessions on 2026-11-08:
 * 55 task notifications, 14 slash commands, 6 command outputs, 6 shell
 * commands, 6 compaction summaries and 1 interruption, against 165 prompts.
 * A human turn that starts with one of these is an event, not a prompt: it
 * gets no number, no place in the prompt list and no count.
 */
export const HARNESS_PREFIXES = [
  "<task-notification>",
  "<command-name>",
  "<command-message>",
  "<command-args>",
  "<local-command-stdout>",
  "<local-command-stderr>",
  "<local-command-caveat>",
  "<bash-input>",
  "<bash-stdout>",
  "<bash-stderr>",
  "<user-prompt-submit-hook>",
  "Caveat: The messages below were generated by the user while running local commands",
  "This session is being continued from a previous conversation",
  "[Request interrupted by user",
  "Stop hook feedback:",
  "SubagentStop hook feedback:",
  // Codex writes its environment and AGENTS.md as user messages.
  "<environment_context>",
  "<user_instructions>",
] as const;

/**
 * The same test in SQL, over a column named `text`, for the counts and the
 * prompt list. The prefixes are constants above, with no quote in them.
 */
export const HARNESS_SQL = `(${HARNESS_PREFIXES.map(
  (prefix) => `substr(ltrim(text), 1, ${prefix.length}) = '${prefix}'`,
).join(" OR ")})`;

export function isHarnessText(text: string): boolean {
  const start = text.trimStart();
  return HARNESS_PREFIXES.some((prefix) => start.startsWith(prefix));
}

/**
 * How an event reads: one line, an optional bit of code in it, and what
 * folds under it. `hidden` is for text that only instructs the model.
 */
export type HarnessEvent = {
  label: string;
  code?: string;
  detail?: string;
  /** The detail is Markdown, as a compaction summary is. */
  markdown?: boolean;
  failed?: boolean;
  hidden?: boolean;
  /**
   * The event sent the agent back to work, so what follows answers it rather
   * than the prompt. After a background task the agent reports a result,
   * which is an answer of its own; after a Stop hook it does what the hook
   * asked, which never is.
   */
  continues?: "task" | "hook";
};

function tagsIn(text: string): Map<string, string> {
  const tags = new Map<string, string>();
  for (const match of text.matchAll(/<([a-z][a-z_-]*)>([\s\S]*?)<\/\1>/g))
    if (!tags.has(match[1])) tags.set(match[1], match[2].trim());
  return tags;
}

const TASK_FIELDS: [string, string][] = [
  ["task-id", "Task"],
  ["tool-use-id", "Tool call"],
  ["output-file", "Output"],
];

/** The event a harness turn stands for, or null for a prompt the person wrote. */
export function harnessEvent(text: string): HarnessEvent | null {
  if (!isHarnessText(text)) return null;
  const start = text.trimStart();
  if (start.startsWith("Caveat:") || start.startsWith("<local-command-caveat>"))
    return { label: "", hidden: true };
  if (start.startsWith("[Request interrupted"))
    return {
      label: start.includes("tool use")
        ? "Interrupted during a tool call"
        : "Interrupted",
    };
  const feedback = start.match(/^(Stop|SubagentStop) hook feedback:\s*/);
  if (feedback)
    return {
      label: `${feedback[1]} hook sent the agent back to work`,
      detail: start.slice(feedback[0].length) || undefined,
      continues: "hook",
    };
  if (start.startsWith("This session is being continued"))
    return {
      label: "Continued from an earlier session",
      detail: start,
      markdown: true,
    };
  const tags = tagsIn(start);
  if (tags.has("task-notification")) {
    const inner = tagsIn(tags.get("task-notification") ?? "");
    const status = inner.get("status");
    const summary = inner.get("summary");
    const detail = TASK_FIELDS.filter(([key]) => inner.get(key))
      .map(([key, label]) => `${label}: ${inner.get(key)}`)
      .join("\n");
    return {
      label: summary
        ? `Background task: ${summary}`
        : `Background task ${status ?? "finished"}`,
      detail: detail || undefined,
      failed: status === "failed" || /exit code [1-9]/.test(summary ?? ""),
      continues: "task",
    };
  }
  if (tags.has("command-name") || tags.has("command-message")) {
    const name = tags.get("command-name") || `/${tags.get("command-message")}`;
    const args = tags.get("command-args");
    return { label: "Ran", code: args ? `${name} ${args}` : name };
  }
  if (tags.has("bash-input"))
    return { label: "Ran", code: `! ${tags.get("bash-input")}` };
  if (tags.has("bash-stdout") || tags.has("bash-stderr")) {
    const output = [tags.get("bash-stdout"), tags.get("bash-stderr")]
      .filter(Boolean)
      .join("\n");
    return {
      label: output ? "Shell output" : "Shell output (empty)",
      detail: output || undefined,
      failed: Boolean(tags.get("bash-stderr")),
    };
  }
  if (tags.has("local-command-stdout") || tags.has("local-command-stderr")) {
    const output = [
      tags.get("local-command-stdout"),
      tags.get("local-command-stderr"),
    ]
      .filter(Boolean)
      .join("\n");
    return {
      label: output ? "Command output" : "Command output (empty)",
      detail: output || undefined,
      failed: Boolean(tags.get("local-command-stderr")),
    };
  }
  if (tags.has("environment_context"))
    return {
      label: "Environment",
      detail: tags.get("environment_context") || undefined,
    };
  if (tags.has("user_instructions"))
    return {
      label: "Instructions",
      detail: tags.get("user_instructions") || undefined,
    };
  const hook = tags.get("user-prompt-submit-hook");
  return { label: "Prompt hook output", detail: hook || undefined };
}

export type TranscriptBlock =
  | { type: "text"; turn: TranscriptTurn }
  | { type: "error"; turn: TranscriptTurn }
  | {
      type: "tools";
      turns: TranscriptTurn[];
      counts: ToolCount[];
      errors: number;
      firstAt: number | null;
      lastAt: number | null;
    }
  | { type: "gap"; seconds: number; position: number }
  | { type: "event"; turn: TranscriptTurn; event: HarnessEvent }
  | { type: "thinking"; turn: TranscriptTurn }
  | { type: "system"; turns: TranscriptTurn[] };

export type Exchange = {
  /** The human turn that opens it; null for turns before the first prompt. */
  prompt: TranscriptTurn | null;
  blocks: TranscriptBlock[];
  errors: number;
  tools: number;
};

/** `mcp__plugin_valise_valise__claim_todo` reads as `valise · claim_todo`. */
export function toolLabel(name: string | null): string {
  if (!name) return "tool";
  if (!name.startsWith("mcp__")) return name;
  const parts = name.split("__");
  const tool = parts.at(-1) ?? name;
  const server = parts
    .slice(1, -1)
    .join("__")
    .replace(/^plugin_[^_]+_/, "")
    .replace(/^claude_ai_/, "")
    .replaceAll("_", " ");
  return server ? `${server} · ${tool}` : tool;
}

export function countTools(turns: readonly TranscriptTurn[]): ToolCount[] {
  const counts = new Map<string, number>();
  for (const turn of turns) {
    if (turn.kind !== "tool_call") continue;
    const tool = toolLabel(turn.toolName);
    counts.set(tool, (counts.get(tool) ?? 0) + 1);
  }
  return [...counts]
    .map(([tool, count]) => ({ tool, count }))
    .sort((a, b) => b.count - a.count || a.tool.localeCompare(b.tool));
}

/** "Bash ×5, Read ×2, Edit" — the run's header, most used first. */
export function toolSummary(counts: readonly ToolCount[], max = 4): string {
  const shown = counts
    .slice(0, max)
    .map(({ tool, count }) => (count > 1 ? `${tool} ×${count}` : tool));
  const rest = counts.slice(max).reduce((sum, { count }) => sum + count, 0);
  return rest ? `${shown.join(", ")}, ${rest} more` : shown.join(", ");
}

/**
 * Group a page of turns into exchanges. A human turn opens one; assistant
 * text and API errors stand alone; consecutive tool calls and tool errors
 * fold into one block, and so do consecutive system turns; an idle stretch longer than `GAP_SECONDS` splits a run
 * and shows as a divider.
 */
export function groupExchanges(turns: readonly TranscriptTurn[]): Exchange[] {
  const exchanges: Exchange[] = [];
  let current: Exchange | null = null;
  let run: TranscriptTurn[] = [];
  let system: TranscriptTurn[] = [];
  let previousAt: number | null = null;

  const open = (prompt: TranscriptTurn | null) => {
    current = { prompt, blocks: [], errors: 0, tools: 0 };
    exchanges.push(current);
    return current;
  };
  const flush = () => {
    if (run.length === 0) return;
    const target = current ?? open(null);
    const times = run
      .map((turn) => turn.at)
      .filter((at): at is number => at !== null);
    const errors = run.filter((turn) => turn.kind === "tool_error").length;
    target.blocks.push({
      type: "tools",
      turns: run,
      counts: countTools(run),
      errors,
      firstAt: times.length ? Math.min(...times) : null,
      lastAt: times.length ? Math.max(...times) : null,
    });
    target.errors += errors;
    target.tools += run.filter((turn) => turn.kind === "tool_call").length;
    run = [];
  };
  // System text arrives in bursts and in the middle of tool runs; it folds
  // into one block and never splits a run, so it lands after the run.
  const flushSystem = () => {
    if (system.length === 0) return;
    (current ?? open(null)).blocks.push({ type: "system", turns: system });
    system = [];
  };

  for (const turn of turns) {
    if (turn.at !== null && previousAt !== null) {
      const idle = turn.at - previousAt;
      if (idle > GAP_SECONDS) {
        flush();
        flushSystem();
        (current ?? open(null)).blocks.push({
          type: "gap",
          seconds: idle,
          position: turn.position,
        });
      }
    }
    if (turn.at !== null) previousAt = turn.at;
    if (turn.kind === "system") {
      system.push(turn);
      continue;
    }
    if (turn.kind === "tool_call" || turn.kind === "tool_error") {
      if (run.length === 0) flushSystem();
      run.push(turn);
      continue;
    }
    flush();
    flushSystem();
    if (turn.kind === "human") {
      const event = harnessEvent(turn.text);
      if (event === null) open(turn);
      else if (!event.hidden)
        (current ?? open(null)).blocks.push({ type: "event", turn, event });
      continue;
    }
    const target = current ?? open(null);
    if (turn.kind === "api_error") {
      target.blocks.push({ type: "error", turn });
      target.errors += 1;
    } else if (turn.kind === "thinking") {
      target.blocks.push({ type: "thinking", turn });
    } else {
      target.blocks.push({ type: "text", turn });
    }
  }
  flush();
  flushSystem();
  return exchanges;
}

/**
 * The replies that answer something, by block index. An exchange splits
 * where an event sent the agent back to work. The prompt's stretch and each
 * background task's stretch end in an answer, their last reply; everything
 * before it there is a note. A Stop hook's stretch has no answer: what the
 * agent does for the hook is never the reply to the prompt.
 */
export function answerIndexes(exchange: Exchange): Set<number> {
  const answers = new Set<number>();
  let answering = true;
  let last = -1;
  const close = () => {
    if (answering && last >= 0) answers.add(last);
    last = -1;
  };
  for (const [index, block] of exchange.blocks.entries()) {
    if (block.type === "event" && block.event.continues) {
      close();
      answering = block.event.continues === "task";
    } else if (block.type === "text") last = index;
  }
  close();
  return answers;
}

/** "1h 12m", "4m", "35s": a span a reader takes in at a glance. */
export function spanLabel(seconds: number): string {
  const s = Math.max(0, Math.round(seconds));
  if (s < 60) return `${s}s`;
  const minutes = Math.round(s / 60);
  if (minutes < 60) return `${minutes}m`;
  const hours = Math.floor(minutes / 60);
  const rest = minutes % 60;
  if (hours < 48) return rest ? `${hours}h ${rest}m` : `${hours}h`;
  return `${Math.round(hours / 24)}d`;
}

/** A Valise item a turn names: `todo:tdo_…`, `memory:mem_…`, `skill:…`. */
export type ItemMention = { id: string; position: number };

const ITEM_ID = /\b(todo:tdo_[\w-]+|memory:mem_[\w-]+|subject:sub_[\w-]+)/g;

/** Every Valise id the turns name, first mention first, each once. */
export function itemMentions(
  turns: readonly Pick<TranscriptTurn, "text" | "position">[],
): ItemMention[] {
  const seen = new Map<string, number>();
  for (const turn of turns) {
    for (const match of turn.text.matchAll(ITEM_ID)) {
      if (!seen.has(match[1])) seen.set(match[1], turn.position);
    }
  }
  return [...seen].map(([id, position]) => ({ id, position }));
}

const FILE_TOOLS = new Set([
  "Read",
  "Edit",
  "MultiEdit",
  "Write",
  "NotebookEdit",
]);
const WRITE_TOOLS = new Set(["Edit", "MultiEdit", "Write", "NotebookEdit"]);

export type FileTouch = { path: string; reads: number; writes: number };

/**
 * Files the session read or changed, from the `file_path:` summary the CLI
 * keeps on Read, Edit and Write calls. Paths under `cwd` read relative to it.
 */
export function filesTouched(
  turns: readonly Pick<TranscriptTurn, "kind" | "toolName" | "text">[],
  cwd: string | null,
): FileTouch[] {
  const files = new Map<string, FileTouch>();
  for (const turn of turns) {
    if (turn.kind !== "tool_call" || !turn.toolName) continue;
    if (!FILE_TOOLS.has(turn.toolName)) continue;
    const match = /^(?:file_path|path): (.+)$/.exec(turn.text.trim());
    if (!match) continue;
    let path = match[1].trim();
    if (cwd && path.startsWith(`${cwd}/`)) path = path.slice(cwd.length + 1);
    const entry = files.get(path) ?? { path, reads: 0, writes: 0 };
    if (WRITE_TOOLS.has(turn.toolName)) entry.writes += 1;
    else entry.reads += 1;
    files.set(path, entry);
  }
  return [...files.values()].sort(
    (a, b) =>
      b.writes - a.writes ||
      b.reads + b.writes - (a.reads + a.writes) ||
      a.path.localeCompare(b.path),
  );
}

/** Skills the session loaded through Valise's per-skill tools or get_skill. */
export function skillsUsed(
  turns: readonly Pick<TranscriptTurn, "kind" | "toolName" | "text">[],
): string[] {
  const skills = new Set<string>();
  for (const turn of turns) {
    if (turn.kind !== "tool_call" || !turn.toolName) continue;
    const tool = turn.toolName.split("__").at(-1) ?? "";
    if (turn.toolName.startsWith("mcp__") && tool.startsWith("skill_")) {
      skills.add(tool.slice("skill_".length));
    } else if (tool === "get_skill" || turn.toolName === "Skill") {
      // `name: tdd` from the CLI's summary, or `{"skill":"tdd"}` when the
      // input had no key the summary knows.
      const name = /"?(?:name|skill)"?\s*:\s*"?([\w:.-]+)/.exec(turn.text);
      if (name) skills.add(name[1]);
    }
  }
  return [...skills].sort();
}

/** The session's day, in UTC, for grouping a list under day headings. */
export function dayKey(seconds: number): string {
  return new Date(seconds * 1000).toISOString().slice(0, 10);
}

export function dayHeading(day: string, now: number): string {
  const today = dayKey(now);
  const yesterday = dayKey(now - 86_400);
  if (day === today) return "Today";
  if (day === yesterday) return "Yesterday";
  return new Date(`${day}T00:00:00Z`).toLocaleDateString("en-GB", {
    weekday: "long",
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  });
}
